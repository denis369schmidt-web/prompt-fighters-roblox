"""Import fighter, signature, boss and mutator data from the Godot project into Luau data modules.

Usage: python3 tools/import_godot.py <path-to-Ultimate-Prompt-Fighters>/godot/scripts

The Godot scripts are the source of truth for combat numbers. This script reads their dictionary
literals (never executes them), converts them to Luau tables and writes the generated modules to
src/ReplicatedStorage/Shared/Data/Generated/. Re-run it whenever the Godot values change.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ReplicatedStorage" / "Shared" / "Data" / "Generated"

MOVE_FIELDS = ["name", "dmg", "windup", "active", "recovery", "xMin", "xMax", "yMin", "yMax", "angle", "kb"]
# Fields that point at Godot asset files; they are dropped because those assets are not licensed for Roblox.
DROP_KEYS = {"body", "model", "look", "pose", "variant"}


def extract_literal(text: str, header_regex: str) -> str:
    m = re.search(header_regex, text)
    if not m:
        raise SystemExit(f"not found: {header_regex}")
    start = m.end() - 1
    depth, i, in_str = 0, start, False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c in "{[":
            depth += 1
        elif c in "}]":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
        i += 1
    raise SystemExit("unbalanced literal")


def strip_comments(src: str) -> str:
    out, in_str, i = [], False, 0
    while i < len(src):
        c = src[i]
        if in_str:
            out.append(c)
            if c == "\\":
                out.append(src[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            out.append(c)
        elif c == "#":
            while i < len(src) and src[i] != "\n":
                i += 1
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def parse(src: str):
    src = strip_comments(src)
    src = re.sub(r'Color\("#?([0-9a-fA-F]+)"\)', r'"#\1"', src)
    src = re.sub(r",(\s*[}\]])", r"\1", src)
    return json.loads(src)


def clean(value):
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items() if k not in DROP_KEYS}
    if isinstance(value, list):
        return [clean(v) for v in value]
    return value


def lua_key(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) else f'["{k}"]'


def inline_lua(value) -> str:
    if isinstance(value, list):
        return "{ " + ", ".join(inline_lua(v) for v in value) + " }" if value else "{}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        return "{ " + ", ".join(f"{lua_key(k)} = {inline_lua(v)}" for k, v in sorted(value.items())) + " }"
    return to_lua(value)


def to_lua(value, indent=0) -> str:
    pad = "\t" * indent
    if isinstance(value, (list, dict)) and indent > 1:
        flat = inline_lua(value)
        if len(flat) + 4 * indent <= 160:
            return flat
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        if all(not isinstance(v, (dict, list)) for v in value):
            return "{ " + ", ".join(to_lua(v) for v in value) + " }" if value else "{}"
        inner = ",\n".join(pad + "\t" + to_lua(v, indent + 1) for v in value)
        return "{\n" + inner + ",\n" + pad + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = sorted(value.items()) if indent > 0 else value.items()
        inner = ",\n".join(f"{pad}\t{lua_key(k)} = {to_lua(v, indent + 1)}" for k, v in items)
        return "{\n" + inner + ",\n" + pad + "}"
    raise TypeError(type(value))


def move_record(arr):
    rec = dict(zip(MOVE_FIELDS, arr[:11]))
    rec["extras"] = clean(arr[11]) if len(arr) > 11 else {}
    return rec


def write(name: str, doc: str, value):
    OUT.mkdir(parents=True, exist_ok=True)
    body = (
        "--!strict\n"
        f"-- GENERATED by tools/import_godot.py from the Godot project. Do not edit by hand.\n-- {doc}\n\n"
        f"return {to_lua(value)}\n"
    )
    (OUT / f"{name}.luau").write_text(body, encoding="utf-8")


def main():
    scripts = Path(sys.argv[1])
    pi = (scripts / "prompt_interpreter.gd").read_text(encoding="utf-8")
    kits_src = (scripts / "fighter_kits.gd").read_text(encoding="utf-8")
    sigs_src = (scripts / "signatures.gd").read_text(encoding="utf-8")
    boss_src = (scripts / "bosses.gd").read_text(encoding="utf-8")
    fun_src = (scripts / "fun_modes.gd").read_text(encoding="utf-8")

    presets = parse(extract_literal(pi, r"var fam_configs: Dictionary = \{"))
    kits = parse(extract_literal(kits_src, r"const KITS := \{"))
    default_phys = parse(extract_literal(kits_src, r"const DEFAULT_PHYS := \{"))
    sigs = parse(extract_literal(sigs_src, r"const SIGS := \{"))
    bosses = parse(extract_literal(boss_src, r"const BOSSES := \{"))
    patterns = parse(extract_literal(boss_src, r"const PATTERNS := \{"))
    mutators = parse(extract_literal(fun_src, r"const MUTATORS := \{"))
    combat_src = (scripts / "combat.gd").read_text(encoding="utf-8")
    prog_src = (scripts / "progression.gd").read_text(encoding="utf-8")
    rew_src = (scripts / "rewards.gd").read_text(encoding="utf-8")
    weapons = parse(extract_literal(combat_src, r"const WEAPONS := \{"))
    projectiles = parse(extract_literal(combat_src, r"const PROJECTILES := \{"))
    challenges = parse(extract_literal(prog_src, r"const CHALLENGES := \{"))
    weekly = parse(extract_literal(prog_src, r"const WEEKLY := \{"))
    achievements = parse(extract_literal(prog_src, r"const ACHIEVEMENTS := \{"))
    shop_weapons = parse(extract_literal(rew_src, r"const WEAPONS := \["))
    skins = parse(extract_literal(rew_src, r"const SKINS := \["))
    titles = parse(extract_literal(rew_src, r"const TITLES := \["))

    kit_out = {}
    for fid, kit in kits.items():
        k = clean(kit)
        k["moves"] = {m: move_record(a) for m, a in kit.get("moves", {}).items()}
        kit_out[fid] = k

    preset_out = {}
    for fid, p in presets.items():
        v = p["values"]
        preset_out[fid] = {
            "stats": dict(zip(["vitality", "power", "defense", "speed", "technique"], v)),
            "element": p["element"],
            "weight": p["weight"],
            "standard": {k[4:]: p[k] for k in p if k.startswith("std_")},
            "special": {k[5:]: p[k] for k in p if k.startswith("spec_")},
            "gear": p.get("modules", []),
        }

    write("FighterPresets", "Base stats, element and base attacks per fighter family (prompt_interpreter.gd).", preset_out)
    write("FighterKits", "Movesets, physics, finishers per fighter (fighter_kits.gd).", {"defaultPhys": default_phys, "kits": kit_out})
    write("SignatureParams", "Signature special parameters per fighter (signatures.gd).", clean(sigs))
    write("BossData", "Bosses and their attack patterns (bosses.gd).", {"bosses": clean(bosses), "patterns": clean(patterns)})
    write("MutatorData", "Mutators (fun_modes.gd).", clean(mutators))
    write("WeaponData", "Weapon items and projectiles (combat.gd).", {"weapons": clean(weapons), "projectiles": clean(projectiles)})
    write(
        "ProgressionData",
        "Daily and weekly challenges, achievements (progression.gd).",
        {
            "daily": challenges,
            "weekly": weekly,
            "achievements": {
                k: {"title": v[0], "text": v[1], "stat": v[2], "need": v[3]} for k, v in achievements.items()
            },
        },
    )
    # Skin "look" names a material style; keep it under another key because DROP_KEYS removes "look".
    for skin in skins:
        skin["material"] = skin.pop("look")
    write("RewardData", "Shop weapons, skins and titles (rewards.gd).", {"shopWeapons": shop_weapons, "skins": skins, "titles": titles})
    print(f"presets={len(preset_out)} kits={len(kit_out)} sigs={len(sigs)} bosses={len(bosses)} patterns={len(patterns)} mutators={len(mutators)}")


if __name__ == "__main__":
    main()
